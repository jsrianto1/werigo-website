export function formatCount(n: number, lang: SagaLang) {
  return new Intl.NumberFormat(lang === "id" ? "id-ID" : "en-US", {
    notation: n >= 10000 ? "compact" : "standard",
    maximumFractionDigits: 1,
  }).format(n);
}
